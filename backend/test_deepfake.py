import sys
import os
import io
from PIL import Image

# Adjust path to import backend modules
sys.path.append(os.path.dirname(os.path.abspath(__file__)))

from services.deepfake_analyzer import analyze_deepfake

def test_deepfake_detector():
    print("=== Testing Deepfake Service ===")
    
    # Pre-train the model if not trained, so that weights are available
    from services.deepfake_analyzer import get_cnn_model
    get_cnn_model()
    
    # Test case 1: Standard authentic image (has genuine camera EXIF tags)
    print("\nTest Case 1: Standard Camera Photo (Genuine EXIF)")
    img1 = Image.new("RGB", (128, 128), (150, 180, 200))
    exif1 = img1.getexif()
    exif1[271] = "Sony"        # Make
    exif1[272] = "ILCE-7RM3"   # Model
    buf1 = io.BytesIO()
    img1.save(buf1, format="JPEG", exif=exif1)
    result1 = analyze_deepfake(buf1.getvalue(), "vacation_photo.jpg", "image/jpeg")
    print(f"File: {result1['metadata']['file_name']}")
    print(f"Prediction: {result1['prediction']}")
    print(f"Risk Score: {result1['risk_score']}%")
    print("Feedback:")
    for fb in result1['feedback']:
        print(f" - {fb}")
    # Authentic image should not be flagged as AI Generated
    assert result1['prediction'] in ["Authentic", "Suspicious"], "Standard camera photo should be predicted as Authentic or Suspicious, not AI Generated"
    
    # Test case 2: Image with missing EXIF (leads to warnings, but evaluated on pixel-level features)
    print("\nTest Case 2: Screenshot/Web Image (Missing EXIF)")
    img2 = Image.new("RGB", (128, 128), (120, 120, 120))
    buf2 = io.BytesIO()
    img2.save(buf2, format="PNG")  # PNG has no EXIF by default
    result2 = analyze_deepfake(buf2.getvalue(), "screenshot.png", "image/png")
    print(f"File: {result2['metadata']['file_name']}")
    print(f"Prediction: {result2['prediction']}")
    print(f"Risk Score: {result2['risk_score']}%")
    print("Feedback:")
    for fb in result2['feedback']:
        print(f" - {fb}")
    assert any("Missing EXIF" in msg for msg in result2['feedback']), "Missing EXIF feedback should be present"

    # Test case 3: Image generated by AI (has dall-e signature in EXIF Software tag)
    print("\nTest Case 3: AI Generated Image (DALL-E Signature)")
    img3 = Image.new("RGB", (128, 128), (100, 100, 100))
    exif3 = img3.getexif()
    exif3[305] = "dall-e generator v3"  # Software
    buf3 = io.BytesIO()
    img3.save(buf3, format="JPEG", exif=exif3)
    # Add raw bytes check fallback as well
    payload3 = buf3.getvalue() + b" creator: dall-e"
    result3 = analyze_deepfake(payload3, "fantasy_landscape.png", "image/png")
    print(f"File: {result3['metadata']['file_name']}")
    print(f"Prediction: {result3['prediction']}")
    print(f"Risk Score: {result3['risk_score']}%")
    print("Feedback:")
    for fb in result3['feedback']:
        print(f" - {fb}")
    assert result3['prediction'] == "AI Generated", "Should predict AI Generated for DALL-E tags"
    assert result3['risk_score'] == 100, "Should have 100% risk score"
    
    # Test case 4: Video with FFmpeg metadata (likely deepfake tool generated or suspicious)
    print("\nTest Case 4: Suspect Video (FFmpeg output container)")
    dummy_video_bytes = b"Video container block. ftyp mp42. software: Lavf58.29.100 (ffmpeg conversion tool)."
    result_vid = analyze_deepfake(dummy_video_bytes, "deepfake_swap.mp4", "video/mp4")
    print(f"File: {result_vid['metadata']['file_name']}")
    print(f"Prediction: {result_vid['prediction']}")
    print(f"Risk Score: {result_vid['risk_score']}%")
    print("Feedback:")
    for fb in result_vid['feedback']:
        print(f" - {fb}")
    assert any("FFmpeg" in msg for msg in result_vid['feedback']), "FFmpeg signature feedback should be present"

    print("\n=== Deepfake Service Tests Completed Successfully ===")

if __name__ == "__main__":
    test_deepfake_detector()
